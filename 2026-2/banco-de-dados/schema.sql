-- PostgreSQL 18. Proposta acadêmica do bispo; executar uma vez em banco vazio.
-- Não contém DROP, dados reais, canal de relatórios ou expiração de token.
BEGIN;
CREATE SCHEMA bispo_bd;
REVOKE ALL ON SCHEMA bispo_bd FROM PUBLIC;

CREATE TABLE bispo_bd.usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador text NOT NULL UNIQUE CHECK (btrim(identificador) <> '')
);
CREATE TABLE bispo_bd.usuario_papel (
    usuario_id bigint NOT NULL REFERENCES bispo_bd.usuario(id),
    papel text NOT NULL CHECK (papel IN ('administrador', 'proprietario', 'respondente')),
    PRIMARY KEY (usuario_id, papel)
);
CREATE TABLE bispo_bd.categoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL UNIQUE CHECK (btrim(nome) <> '')
);
CREATE TABLE bispo_bd.pesquisa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietario_id bigint NOT NULL REFERENCES bispo_bd.usuario(id),
    titulo text NOT NULL CHECK (btrim(titulo) <> ''),
    estado text NOT NULL DEFAULT 'rascunho'
        CHECK (estado IN ('rascunho', 'aberta', 'encerrada'))
);
CREATE TABLE bispo_bd.pesquisa_categoria (
    pesquisa_id bigint NOT NULL REFERENCES bispo_bd.pesquisa(id),
    categoria_id bigint NOT NULL REFERENCES bispo_bd.categoria(id),
    PRIMARY KEY (pesquisa_id, categoria_id)
);
CREATE TABLE bispo_bd.questionario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pesquisa_id bigint NOT NULL UNIQUE REFERENCES bispo_bd.pesquisa(id)
);
CREATE TABLE bispo_bd.questao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    questionario_id bigint NOT NULL REFERENCES bispo_bd.questionario(id),
    enunciado text NOT NULL CHECK (btrim(enunciado) <> ''),
    ordem integer NOT NULL CHECK (ordem > 0),
    tipo text NOT NULL CHECK (tipo IN ('unica', 'multipla')),
    obrigatoria boolean NOT NULL DEFAULT true,
    UNIQUE (questionario_id, ordem)
);
CREATE TABLE bispo_bd.opcao (
    questao_id bigint NOT NULL REFERENCES bispo_bd.questao(id),
    numero integer NOT NULL CHECK (numero > 0),
    rotulo text NOT NULL CHECK (btrim(rotulo) <> ''),
    PRIMARY KEY (questao_id, numero)
);
CREATE TABLE bispo_bd.participacao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pesquisa_id bigint NOT NULL REFERENCES bispo_bd.pesquisa(id),
    identidade_id bigint NOT NULL REFERENCES bispo_bd.usuario(id),
    finalizada boolean NOT NULL DEFAULT false,
    UNIQUE (pesquisa_id, identidade_id)
);
CREATE TABLE bispo_bd.token_individual (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participacao_id bigint NOT NULL REFERENCES bispo_bd.participacao(id),
    resumo_sha256 text NOT NULL UNIQUE CHECK (resumo_sha256 ~ '^[0-9a-f]{64}$'),
    consumido boolean NOT NULL DEFAULT false
);
CREATE TABLE bispo_bd.submissao_anonima (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    pesquisa_id bigint NOT NULL REFERENCES bispo_bd.pesquisa(id)
    -- Sem identidade, token, participação, IP ou horário de submissão.
);
CREATE TABLE bispo_bd.resposta_anonima (
    submissao_id uuid NOT NULL REFERENCES bispo_bd.submissao_anonima(id),
    questao_id bigint NOT NULL REFERENCES bispo_bd.questao(id),
    PRIMARY KEY (submissao_id, questao_id)
);
CREATE TABLE bispo_bd.resposta_opcao (
    submissao_id uuid NOT NULL,
    questao_id bigint NOT NULL,
    numero_opcao integer NOT NULL,
    PRIMARY KEY (submissao_id, questao_id, numero_opcao),
    FOREIGN KEY (submissao_id, questao_id)
        REFERENCES bispo_bd.resposta_anonima(submissao_id, questao_id),
    FOREIGN KEY (questao_id, numero_opcao)
        REFERENCES bispo_bd.opcao(questao_id, numero)
);
CREATE INDEX ON bispo_bd.submissao_anonima(pesquisa_id);
CREATE INDEX ON bispo_bd.token_individual(participacao_id);

-- Estrutura congelada fora de rascunho. O bloqueio coordena edição com abertura.
CREATE FUNCTION bispo_bd.proteger_estrutura() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, bispo_bd AS $$
DECLARE
    v_pesquisa bigint;
    v_questionario bigint;
    v_questao bigint;
    v_estado text;
BEGIN
    IF TG_TABLE_NAME = 'questionario' THEN
        IF TG_OP = 'UPDATE' AND NEW.pesquisa_id IS DISTINCT FROM OLD.pesquisa_id THEN
            RAISE EXCEPTION 'Não é permitido mover questionário entre pesquisas';
        END IF;
        IF TG_OP = 'DELETE' THEN v_pesquisa := OLD.pesquisa_id;
        ELSE v_pesquisa := NEW.pesquisa_id; END IF;
    ELSIF TG_TABLE_NAME = 'questao' THEN
        IF TG_OP = 'UPDATE' AND NEW.questionario_id IS DISTINCT FROM OLD.questionario_id THEN
            RAISE EXCEPTION 'Não é permitido mover questão entre questionários';
        END IF;
        IF TG_OP = 'DELETE' THEN v_questionario := OLD.questionario_id;
        ELSE v_questionario := NEW.questionario_id; END IF;
        SELECT pesquisa_id INTO v_pesquisa FROM bispo_bd.questionario WHERE id = v_questionario;
    ELSE
        IF TG_OP = 'UPDATE' AND NEW.questao_id IS DISTINCT FROM OLD.questao_id THEN
            RAISE EXCEPTION 'Não é permitido mover opção entre questões';
        END IF;
        IF TG_OP = 'DELETE' THEN v_questao := OLD.questao_id;
        ELSE v_questao := NEW.questao_id; END IF;
        SELECT q.pesquisa_id INTO v_pesquisa FROM bispo_bd.questao x
            JOIN bispo_bd.questionario q ON q.id = x.questionario_id WHERE x.id = v_questao;
    END IF;
    SELECT estado INTO v_estado FROM bispo_bd.pesquisa WHERE id = v_pesquisa FOR SHARE;
    IF v_estado IS DISTINCT FROM 'rascunho' THEN
        RAISE EXCEPTION 'Estrutura só pode ser editada em rascunho';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
CREATE TRIGGER proteger_questionario BEFORE INSERT OR UPDATE OR DELETE ON bispo_bd.questionario
    FOR EACH ROW EXECUTE FUNCTION bispo_bd.proteger_estrutura();
CREATE TRIGGER proteger_questao BEFORE INSERT OR UPDATE OR DELETE ON bispo_bd.questao
    FOR EACH ROW EXECUTE FUNCTION bispo_bd.proteger_estrutura();
CREATE TRIGGER proteger_opcao BEFORE INSERT OR UPDATE OR DELETE ON bispo_bd.opcao
    FOR EACH ROW EXECUTE FUNCTION bispo_bd.proteger_estrutura();

-- Impede reabrir ou voltar a rascunho após começar a coleta.
CREATE FUNCTION bispo_bd.proteger_estado() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, bispo_bd AS $$
BEGIN
    IF NEW.estado IS DISTINCT FROM OLD.estado AND NOT (
        (OLD.estado = 'rascunho' AND NEW.estado = 'aberta') OR
        (OLD.estado = 'aberta' AND NEW.estado = 'encerrada')) THEN
        RAISE EXCEPTION 'Transição de estado não permitida';
    END IF;
    IF OLD.estado = 'rascunho' AND NEW.estado = 'aberta' THEN
        IF NOT EXISTS (SELECT 1 FROM bispo_bd.questionario q
            JOIN bispo_bd.questao x ON x.questionario_id = q.id WHERE q.pesquisa_id = OLD.id) THEN
            RAISE EXCEPTION 'Pesquisa sem questões';
        END IF;
        IF EXISTS (SELECT 1 FROM bispo_bd.questionario q
            JOIN bispo_bd.questao x ON x.questionario_id = q.id
            WHERE q.pesquisa_id = OLD.id AND NOT EXISTS
                (SELECT 1 FROM bispo_bd.opcao o WHERE o.questao_id = x.id)) THEN
            RAISE EXCEPTION 'Questão fechada sem opções';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER proteger_estado BEFORE UPDATE ON bispo_bd.pesquisa
    FOR EACH ROW EXECUTE FUNCTION bispo_bd.proteger_estado();

-- Único ponto de escrita de respostas concedido à futura conta de execução.
-- A função é atômica dentro da transação do chamador: não faz COMMIT interno.
CREATE FUNCTION bispo_bd.finalizar(p_pesquisa bigint, p_token text, p_respostas jsonb)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, bispo_bd AS $$
DECLARE
    v_controle record;
    v_questionario bigint;
    v_submissao uuid;
    v_item jsonb;
    v_qid bigint;
    v_tipo text;
BEGIN
    IF p_token IS NULL OR p_token = '' THEN RAISE EXCEPTION 'Acesso inválido'; END IF;
    SELECT p.id, p.finalizada, t.id AS token_id, t.consumido
      INTO v_controle FROM bispo_bd.participacao p
      JOIN bispo_bd.token_individual t ON t.participacao_id = p.id
      WHERE p.pesquisa_id = p_pesquisa
        AND t.resumo_sha256 = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
      FOR UPDATE OF p, t;
    IF NOT FOUND THEN RAISE EXCEPTION 'Acesso inválido'; END IF;
    IF v_controle.finalizada OR v_controle.consumido THEN
        RAISE EXCEPTION 'Participação já finalizada';
    END IF;
    SELECT q.id INTO v_questionario FROM bispo_bd.pesquisa p
      JOIN bispo_bd.questionario q ON q.pesquisa_id = p.id
      WHERE p.id = p_pesquisa AND p.estado = 'aberta' FOR SHARE OF p, q;
    IF NOT FOUND THEN RAISE EXCEPTION 'Pesquisa indisponível'; END IF;
    IF p_respostas IS NULL OR jsonb_typeof(p_respostas) <> 'array' THEN
        RAISE EXCEPTION 'Respostas devem ser uma lista';
    END IF;
    IF jsonb_array_length(p_respostas) = 0 THEN RAISE EXCEPTION 'Envio sem respostas'; END IF;
    -- Valida estrutura antes de converter identificadores.
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_respostas) LOOP
        IF jsonb_typeof(v_item) <> 'object'
          OR jsonb_typeof(v_item->'questao_id') IS DISTINCT FROM 'number'
          OR (v_item->>'questao_id') !~ '^[1-9][0-9]*$'
          OR jsonb_typeof(v_item->'opcoes') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Formato de resposta inválido';
        END IF;
        IF jsonb_array_length(v_item->'opcoes') = 0 THEN RAISE EXCEPTION 'Resposta sem opção'; END IF;
        IF EXISTS (SELECT 1 FROM jsonb_array_elements(v_item->'opcoes') o
            WHERE jsonb_typeof(o.value) <> 'number' OR o.value::text !~ '^[1-9][0-9]*$') THEN
            RAISE EXCEPTION 'Número de opção inválido';
        END IF;
        IF EXISTS (SELECT 1 FROM jsonb_array_elements(v_item->'opcoes') o
            GROUP BY o.value HAVING count(*) > 1) THEN RAISE EXCEPTION 'Opção repetida'; END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM jsonb_array_elements(p_respostas) a
        GROUP BY (a.value->>'questao_id')::bigint HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Questão repetida';
    END IF;
    IF EXISTS (SELECT 1 FROM bispo_bd.questao q WHERE q.questionario_id = v_questionario
        AND q.obrigatoria AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_respostas) a
            WHERE (a.value->>'questao_id')::bigint = q.id)) THEN
        RAISE EXCEPTION 'Questão obrigatória ausente';
    END IF;
    -- Demais validações e gravações ficam na mesma transação. Erro de FK faz rollback.
    INSERT INTO bispo_bd.submissao_anonima(pesquisa_id) VALUES (p_pesquisa) RETURNING id INTO v_submissao;
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_respostas) LOOP
        v_qid := (v_item->>'questao_id')::bigint;
        SELECT tipo INTO v_tipo FROM bispo_bd.questao
          WHERE id = v_qid AND questionario_id = v_questionario;
        IF NOT FOUND THEN RAISE EXCEPTION 'Questão fora do questionário'; END IF;
        IF v_tipo = 'unica' AND jsonb_array_length(v_item->'opcoes') <> 1 THEN
            RAISE EXCEPTION 'Questão de seleção única';
        END IF;
        INSERT INTO bispo_bd.resposta_anonima VALUES (v_submissao, v_qid);
        INSERT INTO bispo_bd.resposta_opcao
          SELECT v_submissao, v_qid, o.value::text::integer
          FROM jsonb_array_elements(v_item->'opcoes') o;
    END LOOP;
    UPDATE bispo_bd.token_individual SET consumido = true WHERE id = v_controle.token_id;
    UPDATE bispo_bd.participacao SET finalizada = true WHERE id = v_controle.id;
    RETURN true; -- Não retorna identificador da submissão nem conteúdo anônimo.
END;
$$;
REVOKE ALL ON ALL TABLES IN SCHEMA bispo_bd FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA bispo_bd FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA bispo_bd FROM PUBLIC;
COMMIT;
